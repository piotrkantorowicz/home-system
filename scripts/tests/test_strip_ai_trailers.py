"""AI attribution is removed from commit messages; human co-authors are kept."""

from pathlib import Path
import subprocess
import tempfile
import unittest


HOOK = Path(__file__).resolve().parents[1] / "hooks/strip-ai-trailers.sh"

STRIPPED = [
    "Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>",
    "co-authored-by: Claude <noreply@anthropic.com>",
    "Co-Authored-By: Codex <codex@openai.com>",
    "Co-Authored-By: GitHub Copilot <copilot@github.com>",
    "Claude-Session: abc123",
    "Codex-Session: abc123",
    "🤖 Generated with [Claude Code](https://claude.com/claude-code)",
    "🤖 Generated with Claude Code",
    "Generated by Codex",
]
KEPT = [
    "Co-Authored-By: Jane Doe <jane@example.com>",
    "Generated the migration with dotnet ef",
    "Session: expired tokens are rejected",
]


class StripAiTrailersTests(unittest.TestCase):
    def strip(self, line):
        with tempfile.NamedTemporaryFile("w+", suffix=".msg") as f:
            f.write(f"feat(x): subject\n\nbody\n\n{line}\n")
            f.flush()
            subprocess.run(["bash", str(HOOK), f.name], check=True)
            return Path(f.name).read_text()

    def test_ai_attribution_removed(self):
        for line in STRIPPED:
            with self.subTest(line=line):
                self.assertNotIn(line.split()[0], self.strip(line).split("body")[1])

    def test_human_lines_kept(self):
        for line in KEPT:
            with self.subTest(line=line):
                self.assertIn(line, self.strip(line))


if __name__ == "__main__":
    unittest.main()
